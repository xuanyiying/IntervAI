import {
  Button,
  GlassCard,
  Modal,
  Text,
  Title,
  useToast,
} from '@/components/ui';
import {
  InterviewReport,
  interviewService,
} from '@/services/interview-service';
import React, { useEffect, useState } from 'react';
import { useTranslation } from 'react-i18next';

const DIMENSION_LABELS: { key: string; labelKey: string }[] = [
  { key: 'accuracy', labelKey: 'interview.report.dimensions.accuracy' },
  { key: 'fluency', labelKey: 'interview.report.dimensions.fluency' },
  {
    key: 'logicalThinking',
    labelKey: 'interview.report.dimensions.logical_thinking',
  },
  {
    key: 'professionalKnowledge',
    labelKey: 'interview.report.dimensions.professional_knowledge',
  },
  {
    key: 'communication',
    labelKey: 'interview.report.dimensions.communication',
  },
  { key: 'confidence', labelKey: 'interview.report.dimensions.confidence' },
];

const scoreColor = (score: number) =>
  score >= 80
    ? 'var(--success-color)'
    : score >= 60
      ? 'var(--warning-color)'
      : 'var(--danger-color)';

interface InterviewReportModalProps {
  open: boolean;
  sessionId: string | null;
  onClose: () => void;
}

/**
 * Full interview review report modal: 6-dimension scores,
 * strengths/improvements, per-question analysis and PDF download.
 */
const InterviewReportModal: React.FC<InterviewReportModalProps> = ({
  open,
  sessionId,
  onClose,
}) => {
  const { t } = useTranslation();
  const { error: showError } = useToast();
  const [report, setReport] = useState<InterviewReport | null>(null);
  const [loading, setLoading] = useState(false);
  const [downloading, setDownloading] = useState(false);

  useEffect(() => {
    if (!open || !sessionId) {
      setReport(null);
      return;
    }
    let cancelled = false;
    const loadReport = async (attempt = 0) => {
      try {
        if (cancelled) return;
        setLoading(true);
        const data = await interviewService.getReport(sessionId);
        if (cancelled) return;
        if (data?.analysis?.overallScore != null) {
          setReport(data);
          setLoading(false);
        } else if (attempt < 15) {
          // Report still being generated by the evaluation queue
          setTimeout(() => loadReport(attempt + 1), 2000);
        } else {
          setLoading(false);
        }
      } catch (err) {
        if (cancelled) return;
        if (attempt < 15) {
          setTimeout(() => loadReport(attempt + 1), 2000);
        } else {
          showError(t('interview.report.generating_retry'));
          setLoading(false);
        }
      }
    };
    loadReport();
    return () => {
      cancelled = true;
    };
  }, [open, sessionId, showError]);

  const handleDownload = async () => {
    if (!sessionId) return;
    try {
      setDownloading(true);
      await interviewService.downloadReport(sessionId);
    } catch (err) {
      showError(t('interview.report.download_failed'));
    } finally {
      setDownloading(false);
    }
  };

  const analysis = report?.analysis;

  return (
    <Modal
      open={open}
      onClose={onClose}
      title={t('interview.report.title')}
      width={720}
      footer={
        <div className="flex justify-end gap-3">
          <Button variant="secondary" onClick={onClose}>
            {t('interview.report.close')}
          </Button>
          <Button
            variant="primary"
            onClick={handleDownload}
            loading={downloading}
            disabled={!analysis}
          >
            {t('interview.report.download')}
          </Button>
        </div>
      }
    >
      {loading || !analysis ? (
        <div className="py-12 text-center">
          <div className="animate-spin w-8 h-8 border-2 border-primary border-t-transparent rounded-full mx-auto mb-3" />
          <Text type="secondary">{t('interview.report.generating')}</Text>
        </div>
      ) : (
        <div className="space-y-6">
          <div className="text-center">
            <div
              className="text-4xl font-bold mb-1"
              style={{ color: scoreColor(analysis.overallScore) }}
            >
              {analysis.overallScore}
            </div>
            <Text type="secondary">
              {t('interview.report.overall_summary', {
                answered: report.answeredQuestions,
                total: report.totalQuestions,
              })}
              {report.jobInfo?.title ? ` · ${report.jobInfo.title}` : ''}
            </Text>
          </div>

          <div>
            <Text strong className="block mb-3">
              {t('interview.report.dimensions_title')}
            </Text>
            <div className="space-y-2.5">
              {DIMENSION_LABELS.map(({ key, labelKey }) => {
                const value = (analysis.dimensions as any)?.[key] ?? 0;
                return (
                  <div key={key} className="flex items-center gap-3">
                    <span className="text-sm text-[var(--text-secondary)] w-24 shrink-0">
                      {t(labelKey)}
                    </span>
                    <div className="flex-1 h-2.5 bg-[var(--glass-bg)] rounded-full overflow-hidden">
                      <div
                        className="h-full rounded-full transition-all duration-500"
                        style={{
                          width: `${Math.min(value, 100)}%`,
                          background: scoreColor(value),
                        }}
                      />
                    </div>
                    <span className="text-sm font-medium w-10 text-right">
                      {value}
                    </span>
                  </div>
                );
              })}
            </div>
          </div>

          <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
            {analysis.strengths?.length > 0 && (
              <GlassCard padding="sm" variant="default">
                <Text strong className="block mb-2">
                  {t('interview.report.strengths')}
                </Text>
                <ul className="list-disc list-inside text-sm text-[var(--text-secondary)] space-y-1">
                  {analysis.strengths.map((item, idx) => (
                    <li key={idx}>{item}</li>
                  ))}
                </ul>
              </GlassCard>
            )}
            {analysis.improvements?.length > 0 && (
              <GlassCard padding="sm" variant="warm">
                <Text strong className="block mb-2">
                  {t('interview.report.improvements')}
                </Text>
                <ul className="list-disc list-inside text-sm text-[var(--text-secondary)] space-y-1">
                  {analysis.improvements.map((item, idx) => (
                    <li key={idx}>{item}</li>
                  ))}
                </ul>
              </GlassCard>
            )}
          </div>

          {analysis.detailedAnalysis?.length > 0 && (
            <div>
              <Text strong className="block mb-3">
                {t('interview.report.detailed_analysis')}
              </Text>
              <div
                className="space-y-3"
                style={{ maxHeight: 320, overflowY: 'auto' }}
              >
                {analysis.detailedAnalysis.map((item, idx) => (
                  <GlassCard key={item.questionId || idx} padding="sm">
                    <div className="flex items-start justify-between gap-3 mb-2">
                      <Text strong className="text-sm">
                        {idx + 1}. {item.question}
                      </Text>
                      <span
                        className="text-lg font-bold shrink-0"
                        style={{ color: scoreColor(item.score) }}
                      >
                        {item.score}
                      </span>
                    </div>
                    {item.feedback && (
                      <Text type="secondary" className="text-sm block mb-2">
                        {item.feedback}
                      </Text>
                    )}
                    {item.suggestions?.length > 0 && (
                      <div className="flex flex-wrap gap-1.5">
                        {item.suggestions.map((s, i) => (
                          <span
                            key={i}
                            className="text-xs px-2 py-0.5 rounded-full bg-primary/10 text-primary"
                          >
                            {s}
                          </span>
                        ))}
                      </div>
                    )}
                  </GlassCard>
                ))}
              </div>
            </div>
          )}

          {analysis.recommendations?.length > 0 && (
            <div>
              <Title level={5} style={{ margin: 0 }}>
                {t('interview.report.recommendations')}
              </Title>
              <ul className="list-disc list-inside text-sm text-[var(--text-secondary)] mt-2 space-y-1">
                {analysis.recommendations.map((item, idx) => (
                  <li key={idx}>{item}</li>
                ))}
              </ul>
            </div>
          )}
        </div>
      )}
    </Modal>
  );
};

export default InterviewReportModal;
